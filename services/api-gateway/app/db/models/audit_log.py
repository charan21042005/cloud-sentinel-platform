from typing import Any, Dict, Optional
from uuid import UUID

from sqlalchemy import DateTime, ForeignKey, JSON, String, Text, func
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base
from app.db.mixins import UUIDPrimaryKeyMixin

JSONVariant = JSON().with_variant(JSONB, "postgresql")


class AuditLog(Base, UUIDPrimaryKeyMixin):
    """
    Persisted application audit events. API access is append/list only; the database
    itself does not provide tamper-proof or administrator-resistant storage.
    """

    __tablename__ = "audit_logs"

    event_type: Mapped[str] = mapped_column(String(100), index=True, nullable=False)
    message: Mapped[str] = mapped_column(Text, nullable=False)
    actor_user_id: Mapped[Optional[UUID]] = mapped_column(
        ForeignKey("users.id", ondelete="SET NULL"), index=True, nullable=True
    )
    outcome: Mapped[Optional[str]] = mapped_column(
        String(20), nullable=True, default="success"
    )
    target_type: Mapped[Optional[str]] = mapped_column(String(50), nullable=True)
    target_id: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)
    details: Mapped[Optional[Dict[str, Any]]] = mapped_column(JSONVariant, nullable=True)

    # Timestamp is generated by the database at insert time.
    created_at: Mapped[DateTime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), index=True, nullable=False
    )
